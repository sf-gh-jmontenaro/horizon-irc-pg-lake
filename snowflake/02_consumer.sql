-- Consumer onboarding: one read-only role + service user + PAT per client.

USE ROLE IRC_DEMO_ADMIN;
GRANT USAGE ON DATABASE IRC_DEMO_DB TO ROLE IRC_DEMO_CONSUMER;
GRANT USAGE ON SCHEMA IRC_DEMO_DB.MARKET_DATA TO ROLE IRC_DEMO_CONSUMER;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA IRC_DEMO_DB.MARKET_DATA TO ROLE IRC_DEMO_CONSUMER;
GRANT SELECT ON FUTURE ICEBERG TABLES IN SCHEMA IRC_DEMO_DB.MARKET_DATA TO ROLE IRC_DEMO_CONSUMER;

USE ROLE ACCOUNTADMIN;
CREATE USER IF NOT EXISTS IRC_DEMO_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = IRC_DEMO_CONSUMER
  COMMENT = 'Horizon IRC consumer for local pg_lake demo';
GRANT ROLE IRC_DEMO_CONSUMER TO USER IRC_DEMO_SVC;

-- Demo only: PATs on service users require a network policy by default.
-- In production, attach a network policy allowing the client's egress IPs instead.
CREATE AUTHENTICATION POLICY IF NOT EXISTS IRC_DEMO_DB.MARKET_DATA.IRC_DEMO_PAT_POLICY
  AUTHENTICATION_METHODS = ('PROGRAMMATIC_ACCESS_TOKEN')
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);
ALTER USER IRC_DEMO_SVC SET AUTHENTICATION POLICY IRC_DEMO_DB.MARKET_DATA.IRC_DEMO_PAT_POLICY;

-- The token is shown once; scripts/create_pat.sh writes it to .env.
ALTER USER IRC_DEMO_SVC ADD PROGRAMMATIC ACCESS TOKEN IRC_DEMO_PAT
  ROLE_RESTRICTION = 'IRC_DEMO_CONSUMER'
  DAYS_TO_EXPIRY = 30;
