-- Provider side: Snowflake-managed Iceberg tables on Snowflake storage.
-- Run as ACCOUNTADMIN (creates roles, warehouse, database).

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS IRC_DEMO_ADMIN;
CREATE ROLE IF NOT EXISTS IRC_DEMO_CONSUMER;
GRANT ROLE IRC_DEMO_ADMIN TO ROLE SYSADMIN;
GRANT ROLE IRC_DEMO_CONSUMER TO ROLE IRC_DEMO_ADMIN;
SET my_user = CURRENT_USER();
GRANT ROLE IRC_DEMO_ADMIN TO USER IDENTIFIER($my_user);

CREATE WAREHOUSE IF NOT EXISTS IRC_DEMO_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT OWNERSHIP ON WAREHOUSE IRC_DEMO_WH TO ROLE IRC_DEMO_ADMIN COPY CURRENT GRANTS;

CREATE DATABASE IF NOT EXISTS IRC_DEMO_DB;
GRANT OWNERSHIP ON DATABASE IRC_DEMO_DB TO ROLE IRC_DEMO_ADMIN COPY CURRENT GRANTS;

USE ROLE IRC_DEMO_ADMIN;
USE WAREHOUSE IRC_DEMO_WH;
CREATE SCHEMA IF NOT EXISTS IRC_DEMO_DB.MARKET_DATA;
USE SCHEMA IRC_DEMO_DB.MARKET_DATA;

-- Iceberg v2 + TIMESTAMP_NTZ(6): pg_lake does not read deletion vectors (v3) or nanosecond timestamps.
CREATE OR REPLACE ICEBERG TABLE SECURITIES (
    SECURITY_ID   INT,
    TICKER        STRING,
    ISSUER_NAME   STRING,
    SECTOR        STRING,
    COUNTRY       STRING,
    CURRENCY      STRING,
    LISTED_DATE   DATE
)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = 'SNOWFLAKE_MANAGED';

CREATE OR REPLACE ICEBERG TABLE DAILY_PRICES (
    SECURITY_ID   INT,
    PRICE_DATE    DATE,
    OPEN_PX       DECIMAL(18,4),
    HIGH_PX       DECIMAL(18,4),
    LOW_PX        DECIMAL(18,4),
    CLOSE_PX      DECIMAL(18,4),
    VOLUME        BIGINT,
    LOADED_AT     TIMESTAMP_NTZ(6)
)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = 'SNOWFLAKE_MANAGED';

CREATE OR REPLACE ICEBERG TABLE CORPORATE_ACTIONS (
    ACTION_ID     INT,
    SECURITY_ID   INT,
    ACTION_TYPE   STRING,
    EX_DATE       DATE,
    RATIO_OR_AMT  DECIMAL(18,6)
)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = 'SNOWFLAKE_MANAGED';

-- Seed: 500 securities, ~250 trading days each, a few hundred corporate actions.
INSERT INTO SECURITIES
SELECT seq4() + 1,
       'TKR' || LPAD(seq4() + 1, 4, '0'),
       'Issuer ' || (seq4() + 1),
       ARRAY_CONSTRUCT('Technology','Financials','Healthcare','Energy','Industrials','Consumer','Utilities')[UNIFORM(0, 6, RANDOM())]::STRING,
       ARRAY_CONSTRUCT('US','GB','DE','JP','CA','FR')[UNIFORM(0, 5, RANDOM())]::STRING,
       'USD',
       DATEADD(day, -UNIFORM(400, 9000, RANDOM()), CURRENT_DATE())
FROM TABLE(GENERATOR(ROWCOUNT => 500));

INSERT INTO DAILY_PRICES
WITH days AS (
  SELECT DATEADD(day, -seq4(), DATEADD(day, -1, CURRENT_DATE())) AS d
  FROM TABLE(GENERATOR(ROWCOUNT => 365))
), base AS (
  SELECT s.SECURITY_ID, d.d AS PRICE_DATE,
         (20 + MOD(s.SECURITY_ID * 37, 480)) * (1 + UNIFORM(-0.03::FLOAT, 0.03::FLOAT, RANDOM())) AS px
  FROM SECURITIES s CROSS JOIN days d
  WHERE DAYOFWEEKISO(d.d) <= 5
)
SELECT SECURITY_ID, PRICE_DATE,
       ROUND(px * 0.995, 4), ROUND(px * 1.02, 4), ROUND(px * 0.98, 4), ROUND(px, 4),
       UNIFORM(10000, 5000000, RANDOM()),
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ(6)
FROM base;

INSERT INTO CORPORATE_ACTIONS
SELECT seq4() + 1,
       UNIFORM(1, 500, RANDOM()),
       ARRAY_CONSTRUCT('DIVIDEND','SPLIT','SPINOFF')[UNIFORM(0, 2, RANDOM())]::STRING,
       DATEADD(day, -UNIFORM(1, 360, RANDOM()), CURRENT_DATE()),
       ROUND(UNIFORM(0.05::FLOAT, 3::FLOAT, RANDOM()), 6)
FROM TABLE(GENERATOR(ROWCOUNT => 300));

SELECT 'SECURITIES' t, COUNT(*) FROM SECURITIES
UNION ALL SELECT 'DAILY_PRICES', COUNT(*) FROM DAILY_PRICES
UNION ALL SELECT 'CORPORATE_ACTIONS', COUNT(*) FROM CORPORATE_ACTIONS;
